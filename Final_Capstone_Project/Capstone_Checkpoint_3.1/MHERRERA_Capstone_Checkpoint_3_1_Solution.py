def load_wikipedia_docs(wiki_dir: str = WIKI_DIR) -> list[dict]:
    if not os.path.isdir(wiki_dir):
        print(f"Warning: Wikipedia directory not found at {wiki_dir}")
        return []
    docs = []
    html_files = sorted(f for f in os.listdir(wiki_dir) if f.endswith(".html"))
    print(f"Loading {len(html_files)} Wikipedia articles from {wiki_dir}/ ...")
    for idx, filename in enumerate(html_files, 1):
        try:
            with open(os.path.join(wiki_dir, filename), "r", encoding="utf-8", errors="replace") as fh:
                soup = BeautifulSoup(fh.read(), "html.parser")
            for tag in soup(["script", "style"]):
                tag.decompose()
            text = " ".join(soup.get_text(separator=" ", strip=True).split())
            if text:
                docs.append({"id": filename.replace(".html", ""), "text": text})
        except Exception as exc:
            print(f"  Error reading {filename}: {exc}")
        if idx % 200 == 0 or idx == len(html_files):
            print(f"  Progress: {idx}/{len(html_files)} ({len(docs)} valid)")
    print(f"Loaded {len(docs)} articles.")
    return docs


def load_docs_from_chroma(chroma_dir: str = CHROMA_DIR) -> list[dict]:
    if not os.path.isdir(chroma_dir) or not os.listdir(chroma_dir):
        return []
    db = Chroma(persist_directory=chroma_dir, embedding_function=get_embeddings())
    try:
        results = db.get(include=["documents", "metadatas"])
    except Exception as exc:
        print(f"Warning: could not read persisted Chroma docs: {exc}")
        return []
    docs = []
    for doc_id, text, meta in zip(
        results.get("ids", []), results.get("documents", []), results.get("metadatas", [])
    ):
        if not text:
            continue
        docs.append({"id": str((meta or {}).get("id", doc_id)), "text": text})
    print(f"Loaded {len(docs)} documents from existing Chroma DB at {chroma_dir}/")
    return docs


