def _load_json(path: Path) -> list[dict]:
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def load_split_datasets() -> tuple[Dataset, Dataset]:
    """Build two RAGAS datasets from a single combined variants file.

    Originals come from test_main_questions.json. Paraphrases are the paraphrase-only
    rows of testinputs_variant_questions.json -- i.e., every row whose question text is
    NOT one of the originals. This keeps the originals-vs-paraphrases comparison
    apples-to-apples, since the paraphrases are derived from the same originals.
    """
    if not ORIGINALS_PATH.exists():
        raise FileNotFoundError(f"Originals not found at {ORIGINALS_PATH}")
    if not VARIANTS_PATH.exists():
        raise FileNotFoundError(
            f"Variants file not found at {VARIANTS_PATH}. Generate it first with "
            f"generate_variants.py."
        )

    originals = _load_json(ORIGINALS_PATH)
    original_questions = {o["question"].strip() for o in originals}

    combined = _load_json(VARIANTS_PATH)
    # paraphrases = rows in the combined file that are NOT one of the originals
    paraphrases = [r for r in combined if r["question"].strip() not in original_questions]

    def _to_dataset(name: str, rows: list[dict]) -> Dataset:
        ds = Dataset(name=name, backend="local/csv", root_dir=RAGAS_ROOT)
        for r in rows:
            ds.append({"question": r["question"], "grading_notes": r["grading_notes"]})
        ds.save()
        return ds

    return (
        _to_dataset("wiki_eval_originals", originals),
        _to_dataset("wiki_eval_paraphrases", paraphrases),
    )


